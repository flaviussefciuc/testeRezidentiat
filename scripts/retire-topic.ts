// Freezes live questions into src/app/bank/retired/<topic>.ts before their source
// file is rewritten, and moves their review records to docs/retired-question-reviews.json.
// Usage: node --import tsx scripts/retire-topic.ts <topicId> [--ids id1,id2,...]
// Run it while the old bank files are still imported; then replace those files.
import {existsSync,readFileSync,readdirSync,writeFileSync} from 'node:fs';
import {QUESTIONS} from '../src/app/questions.ts';

const topic=process.argv[2];
const idsArg=process.argv.indexOf('--ids');
const only=idsArg>=0?new Set(process.argv[idsArg+1].split(',')):null;
if(!topic)throw new Error('Usage: retire-topic.ts <topicId> [--ids a,b]');
const live=QUESTIONS.filter(q=>q.topicId===topic&&(!only||only.has(q.id)));
if(!live.length)throw new Error(`No live questions for ${topic}`);

const dir='src/app/bank/retired';
const constName=(t:string)=>'RETIRED_'+t.toUpperCase().replace(/[^A-Z0-9]/g,'_');
const file=`${dir}/${topic}.ts`;
const header=`import type {Question} from '../../models';\n\n// Frozen snapshot: never edit. Old attempts are scored against these exact versions.\nexport const ${constName(topic)}:(Question&Record<string,unknown>)[]=`;
const existing:any[]=existsSync(file)?JSON.parse(readFileSync(file,'utf8').slice(header.length).replace(/;\s*$/,'')):[];
const byId=new Map(existing.map(q=>[q.id,q]));
for(const q of live){
 const prev=byId.get(q.id);
 if(prev&&JSON.stringify(prev)!==JSON.stringify(q))throw new Error(`${q.id} already retired with different content`);
 byId.set(q.id,JSON.parse(JSON.stringify(q)));
}
writeFileSync(file,header+JSON.stringify([...byId.values()],null,1)+';\n');

const topics=readdirSync(dir).filter(f=>f.endsWith('.ts')&&f!=='index.ts').map(f=>f.slice(0,-3)).sort();
writeFileSync(`${dir}/index.ts`,`// Generated by scripts/retire-topic.ts. Frozen copies of published questions that
// were replaced or withdrawn; they keep old attempts and drafts scoreable.
import type {Question} from '../../models';
${topics.map(t=>`import {${constName(t)}} from './${t}';`).join('\n')}

export const RETIRED_QUESTIONS:Question[]=[${topics.map(constName).map(c=>'...'+c).join(',')}];
`);

const ids=new Set(live.map(q=>q.id));
const reviews=JSON.parse(readFileSync('docs/question-reviews.json','utf8'));
const retiredPath='docs/retired-question-reviews.json';
const retired=existsSync(retiredPath)?JSON.parse(readFileSync(retiredPath,'utf8')):[];
const moving=reviews.filter((r:any)=>ids.has(r.questionId));
writeFileSync('docs/question-reviews.json',JSON.stringify(reviews.filter((r:any)=>!ids.has(r.questionId)),null,1)+'\n');
writeFileSync(retiredPath,JSON.stringify([...retired.filter((r:any)=>!ids.has(r.questionId)),...moving],null,1)+'\n');
console.log(`Retired ${live.length} ${topic} questions (${moving.length} reviews moved). Now remove them from the live bank.`);

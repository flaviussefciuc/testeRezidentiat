// Tracks, per original question ID, how the 2026-09 remediation handled the two
// cross-cutting risk groups: items citing a syllabus "până la «…»" cutoff page and
// items relying on a Cadran/Figura/Tabel. Writes docs/remediation-reconciliation.md.
// Usage: node --import tsx scripts/remediation-reconciliation.ts
import {writeFileSync} from 'node:fs';
import {QUESTIONS,RETIRED_QUESTIONS} from '../src/app/questions.ts';
import type {Question} from '../src/app/models';

// Printed pages where the 2026 syllabus stops a chapter "până la" a heading.
const CUTOFF_PAGES:Record<string,number[]>={'Kumar & Clark':[459,619,872,961,972,982,1048,1166,1176],Lawrence:[199,433]};
const BOX=/\b(Cadran|Figura|Fig\.|Tabel)/i;
const isVersion=(id:string)=>/-v\d+$/.test(id);

const originals=new Map<string,Question>();
for(const q of [...RETIRED_QUESTIONS,...QUESTIONS])if(!isVersion(q.id)&&!originals.has(q.id))originals.set(q.id,q);
const live=new Set(QUESTIONS.map(q=>q.id));
const replacement=new Map(QUESTIONS.filter(q=>isVersion(q.id)).map(q=>[(q as any).replaces as string,q]));

const ref=(q:Question)=>(q as any).reference as {book:string;printedPages:number[];section?:string}|undefined;
const cites=(q:Question)=>{const r=ref(q);return !!r&&r.printedPages.some(p=>(CUTOFF_PAGES[r.book]??[]).includes(p));};
const boxed=(q:Question)=>BOX.test([q.stem,ref(q)?.section,(q as any).learningObjective,...((q as any).optionRationales??[])].join(' '));

function status(id:string){
 if(live.has(id))return 'pending (original still live)';
 const v=replacement.get(id);
 if(!v)return 'retired without replacement';
 const r=ref(v)!;
 return `replaced by ${v.id} (p. ${r.printedPages.join(', ')}; expressions verified on the cited page)`;
}

function section(title:string,items:Question[]){
 const rows=items.sort((a,b)=>a.id.localeCompare(b.id)).map(q=>`| ${q.id} | ${q.topicId} | ${status(q.id)} |`);
 const pending=items.filter(q=>live.has(q.id)).length;
 return `## ${title}\n\n${items.length} items, ${items.length-pending} resolved, ${pending} pending.\n\n| Original ID | Topic | Status |\n|---|---|---|\n${rows.join('\n')}\n`;
}

const all=[...originals.values()];
const md=`# Remediation reconciliation

Generated by \`scripts/remediation-reconciliation.ts\`. "Resolved" means the original was retired, either
without replacement or with a \`-vN\` version whose cited page was re-read and whose textbook expressions
were found on that page. Cutoff-page and box checks for each topic are logged in \`docs/source-discrepancies.md\`.

${section('Items citing a syllabus cutoff page',all.filter(cites))}
${section('Items relying on a Cadran / Figura / Tabel',all.filter(boxed))}`;
writeFileSync('docs/remediation-reconciliation.md',md);
const c=all.filter(cites),b=all.filter(boxed);
console.log(`cutoff: ${c.length} (${c.filter(q=>live.has(q.id)).length} pending); boxes: ${b.length} (${b.filter(q=>live.has(q.id)).length} pending)`);

"""Generate light/dark colour tokens for src/styles.css.

Every raw colour literal in the stylesheet is replaced by a variable named after it
(#e4e8e1 -> var(--k-e4e8e1)). The light theme keeps the original value; the dark theme
is derived in OKLCH: hue is preserved, lightness is remapped so that light surfaces
become dark surfaces (white panels slightly lifted above the page) and dark text
becomes light text, and chroma is softened on dark surfaces.

The script is idempotent: write new CSS with plain hex colours, then run
    python scripts/theme-tokens.py
and the new colours join the generated token block.
"""
import math, re, sys
from pathlib import Path

CSS = Path(__file__).resolve().parent.parent / 'src' / 'styles.css'
START, END = '/* @theme-tokens:start', '/* @theme-tokens:end */'
# Elements that are already dark, coloured "objects" keep their light-theme palette.
KEEP_LIGHT = ['.hero', '.brand-mark', '.book-cover', '.keep-palette']
# Hand-tuned dark values where the formula is not the best choice.
OVERRIDES = {'f7f8f5': '#121714', 'ffffff': '#1a201c', 'ffffffb3': '#1a201cd9', 'fff': '#1a201c'}

def expand(h):
    h = h.lower().lstrip('#')
    if len(h) in (3, 4): h = ''.join(c * 2 for c in h)
    return h

def srgb_to_lin(c): return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
def lin_to_srgb(c): return 12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055

def to_oklch(r, g, b):
    r, g, b = (srgb_to_lin(x) for x in (r, g, b))
    l = 0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b
    m = 0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b
    s = 0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b
    l, m, s = (math.copysign(abs(x) ** (1 / 3), x) for x in (l, m, s))
    L = 0.2104542553 * l + 0.7936617850 * m - 0.0040720468 * s
    a = 1.9779984951 * l - 2.4285922050 * m + 0.4505937099 * s
    bb = 0.0259040371 * l + 0.7827717662 * m - 0.8086757660 * s
    return L, math.hypot(a, bb), math.atan2(bb, a)

def from_oklch(L, C, h):
    a, b = C * math.cos(h), C * math.sin(h)
    l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s = (L - 0.0894841775 * a - 1.2914855480 * b) ** 3
    r = 4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s
    g = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s
    bl = -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s
    return r, g, bl

def in_gamut(rgb): return all(-1e-4 <= x <= 1 + 1e-4 for x in rgb)

def dark_of(hexv):
    if hexv in OVERRIDES: return OVERRIDES[hexv]
    rgb = [int(hexv[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    alpha = hexv[6:8]
    L, C, h = to_oklch(*rgb)
    # Translucent dark colours are shadows and backdrops: they stay dark.
    if alpha and L < 0.5: return '#' + hexv
    # Light surfaces and borders -> dark surfaces; mid tones and text -> light.
    L2 = 0.215 + (1 - L) * 1.6 if L >= 0.8 else min(0.95, 0.535 + (0.8 - L) * 0.77)
    if L2 < 0.4: C *= 0.75
    while C > 0 and not in_gamut([lin for lin in from_oklch(L2, C, h)]):
        C -= 0.002
    lin = from_oklch(L2, max(C, 0), h)
    out = ''.join(f'{round(255 * min(1.0, max(0.0, lin_to_srgb(min(1.0, max(0.0, x)))))):02x}' for x in lin)
    return '#' + out + alpha

def main():
    css = CSS.read_text(encoding='utf-8')
    if START in css:
        head, rest = css.split(START, 1)
        _, tail = rest.split(END, 1)
        css = head.rstrip('\n') + tail
    css = css.replace('rgba(255,255,255,.7)', '#ffffffb3')
    known = {}
    for m in re.finditer(r'var\(--k-([0-9a-f]{6}(?:[0-9a-f]{2})?)\)', css):
        known[m.group(1)] = True
    def repl(m):
        h = expand(m.group(0))
        if len(h) not in (6, 8): return m.group(0)
        known[h] = True
        return f'var(--k-{h})'
    # Replace colour literals outside the token definitions.
    css = re.sub(r'#[0-9a-fA-F]{3,8}\b', repl, css)
    keys = sorted(known)
    light = ';'.join(f'--k-{k}:#{k}' for k in keys)
    dark = ';'.join(f'--k-{k}:{dark_of(k)}' for k in keys)
    keep = ','.join(f':root[data-theme=dark] {s}' for s in KEEP_LIGHT)
    # Semantic variables (--ink, --lime...) resolve where they are declared, so the
    # keep-light elements re-declare them against the light tokens.
    semantic = sorted(set(re.findall(r'(--(?!k-)[\w-]+):(var\(--k-[0-9a-f]+\))', css)))
    light_keep = light + ''.join(f';{n}:{v}' for n, v in semantic)
    block = (f"{START} — generated by scripts/theme-tokens.py; edit colours in the rules below */\n"
             f":root{{{light}}}\n"
             f":root[data-theme=dark]{{color-scheme:dark;{dark}}}\n"
             f"{keep}{{{light_keep}}}\n{END}\n")
    # Insert after the font @import (which must stay first).
    lines = css.split('\n', 1)
    css = lines[0] + '\n' + block + lines[1].lstrip('\n')
    CSS.write_text(css, encoding='utf-8', newline='')
    print(f'{len(keys)} colour tokens written to {CSS.name}')

if __name__ == '__main__':
    sys.exit(main())

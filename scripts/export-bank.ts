// Serializes the question bank for the browser.
// The authored TypeScript bank stays the single source of truth (tests and audits use it),
// but shipping it as code made every page download and evaluate ~12 MB of JavaScript.
// The SPA instead gets:
//  - src/app/bank-index.generated.ts: a ~160 KB index (id → topic, answer key, active flag)
//    that is enough to score any saved attempt and to build new sessions;
//  - public/bank/active.json and public/bank/history.json: full question text, fetched only
//    by the pages that display questions, and cached by the browser.
import {createHash} from 'node:crypto';
import {mkdirSync,writeFileSync} from 'node:fs';
import {QUESTIONS,QUESTION_HISTORY} from '../src/app/questions.ts';
import {TOPICS} from '../src/app/topics.ts';
import type {Question} from '../src/app/models.ts';
import {encodeEntry} from '../src/app/bank-codec.ts';

const topicOrder=TOPICS.map(t=>t.id);
const activeIds=new Set(QUESTIONS.map(q=>q.id));
// Sourced questions rebuild their explanation from the option rationales, so the
// duplicated text is dropped from the payload; legacy questions keep theirs.
const slim=(q:Question)=>('optionRationales' in q?{...q,explanation:''}:q);
const active=QUESTIONS.map(slim);
const history=QUESTION_HISTORY.filter(q=>!activeIds.has(q.id)).map(slim);
const activeJson=JSON.stringify(active),historyJson=JSON.stringify(history);
const version=createHash('sha256').update(activeJson).update(historyJson).digest('hex').slice(0,12);

const index:Record<string,number>={};
for(const q of QUESTION_HISTORY)index[q.id]=encodeEntry(topicOrder,q,activeIds.has(q.id));

// Sibling questions: same chapter, mostly the same words (e.g. two rows of one score table).
// Served together they cue each other, so sessions never pair them.
const STOP=new Set('si sau de la in cu pe din al ale a o un una este sunt se care pentru prin mai cel cea ce nu la lui ei sa fi'.split(' '));
const words=(s:string)=>new Set(s.toLowerCase().normalize('NFD').replace(/\p{Diacritic}/gu,'').split(/[^a-z0-9]+/).filter(t=>t.length>2&&!STOP.has(t)));
const siblings:[string,string][]=[];
const byTopic=new Map<string,{id:string;w:Set<string>}[]>();
for(const q of QUESTIONS)byTopic.set(q.topicId,[...(byTopic.get(q.topicId)??[]),{id:q.id,w:words(q.stem+' '+q.options.join(' '))}]);
for(const list of byTopic.values())for(let i=0;i<list.length;i++)for(let j=i+1;j<list.length;j++){let n=0;for(const x of list[i].w)if(list[j].w.has(x))n++;if(n/(list[i].w.size+list[j].w.size-n)>=0.5)siblings.push([list[i].id,list[j].id]);}

mkdirSync('public/bank',{recursive:true});
writeFileSync('public/bank/active.json',activeJson);
writeFileSync('public/bank/history.json',historyJson);
writeFileSync('src/app/bank-index.generated.ts',`// Generated by scripts/export-bank.ts — do not edit.\nexport const BANK_VERSION=${JSON.stringify(version)};\nexport const TOPIC_ORDER:string[]=${JSON.stringify(topicOrder)};\nexport const INDEX:Record<string,number>=${JSON.stringify(index)};\nexport const SIBLINGS:[string,string][]=${JSON.stringify(siblings)};\n`);
console.info(`Bank exported: ${active.length} active, ${history.length} historical versions (v${version}), ${siblings.length} sibling pairs.`);
